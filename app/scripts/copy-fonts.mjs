// Copies the fonts the core renderer bundles into the webview and writes an
// @font-face sheet for them, so the SVG preview uses exactly the type the
// export does. Family, weight and style are read from each font file itself,
// because file names ("IBMPlexMono-Medium") do not reliably give the family.

import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const APP_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const CORE_FONTS_DIR = join(APP_DIR, "..", "crates", "core", "assets", "fonts");
const OUT_DIR = join(APP_DIR, "public", "fonts");

// OpenType name ids: 1 is the legacy family, 16 the typographic family.
const NAME_FAMILY = 1;
const NAME_TYPOGRAPHIC_FAMILY = 16;
const ITALIC_BIT = 1;

function tableOffsets(font) {
  const tables = {};
  const count = font.readUInt16BE(4);
  for (let i = 0; i < count; i++) {
    const record = 12 + i * 16;
    tables[font.toString("latin1", record, record + 4)] = font.readUInt32BE(record + 8);
  }

  return tables;
}

function readName(font, nameTable, wantedId) {
  const count = font.readUInt16BE(nameTable + 2);
  const stringsStart = nameTable + font.readUInt16BE(nameTable + 4);
  for (let i = 0; i < count; i++) {
    const record = nameTable + 6 + i * 12;
    const platform = font.readUInt16BE(record);
    const nameId = font.readUInt16BE(record + 6);
    if (nameId !== wantedId || platform !== 3) continue;

    const length = font.readUInt16BE(record + 8);
    const start = stringsStart + font.readUInt16BE(record + 10);
    // Windows-platform names are UTF-16 big endian.
    return font.subarray(start, start + length).swap16().toString("utf16le");
  }

  return null;
}

function describe(path) {
  const font = Buffer.from(readFileSync(path));
  const tables = tableOffsets(font);
  const family =
    readName(Buffer.from(font), tables.name, NAME_TYPOGRAPHIC_FAMILY) ??
    readName(Buffer.from(font), tables.name, NAME_FAMILY);
  const weight = font.readUInt16BE(tables["OS/2"] + 4);
  const isItalic = (font.readUInt16BE(tables["OS/2"] + 62) & ITALIC_BIT) !== 0;

  return { family, weight, style: isItalic ? "italic" : "normal" };
}

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

let css = "/* Generated by scripts/copy-fonts.mjs from crates/core/assets/fonts. */\n";
let files = [];
try {
  files = readdirSync(CORE_FONTS_DIR).filter((name) => /\.(ttf|otf)$/i.test(name));
} catch {
  console.warn(`No fonts found in ${CORE_FONTS_DIR}; the preview falls back to system type.`);
}

for (const name of files.sort()) {
  copyFileSync(join(CORE_FONTS_DIR, name), join(OUT_DIR, name));
  const { family, weight, style } = describe(join(CORE_FONTS_DIR, name));
  css += `@font-face { font-family: "${family}"; src: url("./${name}"); font-weight: ${weight}; font-style: ${style}; font-display: block; }\n`;
}

// The fonts' licences (SIL OFL) travel with them into the app.
for (const name of readdirSync(CORE_FONTS_DIR).filter((name) => /\.txt$/i.test(name))) {
  copyFileSync(join(CORE_FONTS_DIR, name), join(OUT_DIR, name));
}

writeFileSync(join(OUT_DIR, "fonts.css"), css);
console.log(`Copied ${files.length} fonts into public/fonts.`);
